-- Schema untuk Halaman 2 (Fullstack PDP dengan PostgreSQL)
-- Struktur tabel products untuk katalog produk (Variation & Features berformat JSONB)

CREATE TABLE IF NOT EXISTS products (
  id SERIAL PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  photo VARCHAR(255) NOT NULL DEFAULT 'unica.jpeg',
  variation JSONB NOT NULL DEFAULT '[]'::jsonb,
  description TEXT,
  more_information TEXT,
  features JSONB NOT NULL DEFAULT '[]'::jsonb,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Pastikan kolom-kolom baru tersedia jika tabel products sebelumnya dibuat dengan skema lama
ALTER TABLE products ADD COLUMN IF NOT EXISTS photo VARCHAR(255) DEFAULT 'unica.jpeg';
ALTER TABLE products ADD COLUMN IF NOT EXISTS variation JSONB DEFAULT '[]'::jsonb;
ALTER TABLE products ADD COLUMN IF NOT EXISTS more_information TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS features JSONB DEFAULT '[]'::jsonb;

-- Lepaskan constraint NOT NULL pada kolom lama agar kompatibel
DO $$ 
BEGIN
  IF EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_name = 'products' AND column_name = 'price'
  ) THEN
    ALTER TABLE products ALTER COLUMN price DROP NOT NULL;
    ALTER TABLE products ALTER COLUMN price SET DEFAULT 0;
  END IF;

  IF EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_name = 'products' AND column_name = 'image_url'
  ) THEN
    ALTER TABLE products ALTER COLUMN image_url DROP NOT NULL;
    ALTER TABLE products ALTER COLUMN image_url SET DEFAULT 'unica.jpeg';
  END IF;

  -- Izinkan insert manual pada id identity
  IF EXISTS (
    SELECT 1 FROM information_schema.columns 
    WHERE table_name = 'products' AND column_name = 'id' AND is_identity = 'YES'
  ) THEN
    ALTER TABLE products ALTER COLUMN id SET GENERATED BY DEFAULT;
  END IF;
END $$;

-- Index untuk mempercepat query berdasarkan nama
CREATE INDEX IF NOT EXISTS idx_products_name ON products (name);
